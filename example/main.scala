import org.bargsten.tstype.*
import org.bargsten.tstype.TsExpr.TsInterface
import org.bargsten.tstype.syntax.*

/** Runnable end-to-end example for scala-tstype. Models a small blog domain and emits TypeScript declarations split into a few feature
  * files. Demonstrates: case classes with nested references, optional fields, `Seq`, `Map`, an `enum`, a sealed-trait tagged union, a
  * wrapper type projected to a primitive via `TsType.sameAs`, and the `syntax` DSL for shaping a slimmer DTO.
  *
  * Run: `scala-cli run .` Output: `users.ts`, `blog.ts`, `notifications.ts`
  */

// ---- wrapper types projected to TS primitives ----

case class Email(address: String)
given TsType[Email] = TsType.sameAs[Email, String]

// ---- domain ----

enum Role {
  case Admin, Editor, Reader
}

case class User(
    id: Long,
    username: String,
    email: Email,
    passwordHash: String,
    role: Role,
)

case class Comment(
    id: Long,
    author: User,
    body: String,
)

case class Post(
    id: Long,
    author: User,
    title: String,
    body: String,
    tags: Seq[String],
    publishedAt: Option[String],
    viewsByCountry: Map[String, Int],
    comments: Seq[Comment],
)

sealed trait Notification
case class NewComment(commentId: Long) extends Notification
case class Mention(byUser: Long, inPost: Long) extends Notification
case class SystemMessage(text: String) extends Notification

// ---- TypeScript generation ----

/** Public-facing variant of [[User]]: same shape minus `passwordHash`. Built via the syntax DSL on top of the existing derivation, then
  * renamed so it lands in the output as a distinct interface.
  */
val UserPublic: TsType[User] = (TsType.derive[User] - "passwordHash").get match {
  case i: TsInterface => TsType(i.copy(qualifiedName = "UserPublic"))
  case _              => sys.error("derive[User] did not yield a TsInterface")
}

@main
def main(): Unit = {
  val styleOptions = StyleOptions(taggedUnionDiscriminator = Some("kind"))
  val header = "// Auto-generated by the scala-tstype example. Do not edit."

  val users = Seq(
    TsType.derive[Role],
    TsType.derive[User],
    UserPublic,
  )

  val blog = Seq(
    TsType.derive[Post],
    TsType.derive[Comment],
  )

  val notifications = Seq(
    TsType.derive[Notification],
  )

  TsExport.toTypescriptFile(users, "users.ts", styleOptions, header)
  TsExport.toTypescriptFile(blog, "blog.ts", styleOptions, header)
  TsExport.toTypescriptFile(notifications, "notifications.ts", styleOptions, header)

  println("wrote users.ts, blog.ts, notifications.ts")
}
